const dict = { en, km }

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: 'en', setLang: () => {} })

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try { return (localStorage.getItem('lang') as Lang) === 'km' ? 'km' : 'en' } catch { return 'en' }
  })
  useEffect(() => {
    document.documentElement.lang = lang
    try { localStorage.setItem('lang', lang) } catch { /* private mode */ }
  }, [lang])
  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>
}

export function useLang() {
  const { lang, setLang } = useContext(LangContext)
  const t = (k: Key) => dict[lang][k] || dict.en[k]
  /** Picks the Khmer or English variant of a bilingual record. */
  const name = (o: { en: string; km?: string | null }) => (lang === 'km' && o.km ? o.km : o.en)
  const num = (n: number, opts?: Intl.NumberFormatOptions) => n.toLocaleString(lang === 'km' ? 'km-KH' : 'en-GB', opts)
  return { lang, setLang, t, name, num }
}
